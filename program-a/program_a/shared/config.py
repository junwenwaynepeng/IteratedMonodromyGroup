def normalize(v=None):
    L = dict(DEFAULT)
    for k, x in (v or {}).items():
        require(
            k in L and type(x) in (int, float) and math.isfinite(x) and 0 < x <= MAX[k],
            "unsupported/nonfinite/oversized limit " + str(k),
        )
        require(k in FLOAT or type(x) is int, "integer limit " + k)
        L[k] = x
    for k in (
        "tuple_cap",
        "relator_cap",
        "root_seed_states",
        "frontier_cap",
        "constructive_coset_cap",
    ):
        require(L[k] <= L[k + "_max"], "initial cap exceeds ceiling " + k)
    require(
        L["task_slice_seconds"] <= L["task_slice_max_seconds"],
        "task slice exceeds ceiling",
    )
    require(
        L["coset_cap"] <= L["gap_coset_cap_max"], "initial GAP cosets exceed ceiling"
    )
    require(
        L["checkpoint_frontier_nodes"] >= L["frontier_cap_max"],
        "checkpoint must retain whole configured frontier",
    )
    return L
